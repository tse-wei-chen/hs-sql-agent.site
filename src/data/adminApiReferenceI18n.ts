export type AdminApiLocale = keyof typeof adminApiLocales;
export type AdminApiMessages = (typeof adminApiLocales)[AdminApiLocale];

export function getAdminApiMessages(locale: string): AdminApiMessages {
  return adminApiLocales[(locale in adminApiLocales ? locale : "en") as AdminApiLocale];
}

export function getAdminApiGroupLabel(locale: string, tag: string): string {
  const messages = getAdminApiMessages(locale);
  return (messages.groups as Record<string, string>)[tag] ?? tag;
}

export function getHttpStatusLabel(locale: string, status: string, original = ""): string {
  const messages = getAdminApiMessages(locale);
  return (messages.responseLabels as Record<string, string>)[status] ?? original;
}
